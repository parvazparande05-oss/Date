def compatibility_report(type1: str, type2: str) -> dict:
    """برمی‌گرداند: {score, strengths: [...], weaknesses: [...], suggestion: str}"""
    if not type1 or not type2 or len(type1) != 4 or len(type2) != 4:
        return {"score": 50, "strengths": ["هنوز تایپ MBTI کامل ثبت نشده."], "weaknesses": [], "suggestion": ""}

    axes = ["EI", "SN", "TF", "JP"]
    weights = {"EI": 15, "SN": 30, "TF": 25, "JP": 20}
    score = 10
    strengths, weaknesses = [], []

    for i, axis in enumerate(axes):
        same = type1[i] == type2[i]
        if axis == "EI":
            score += weights[axis] * (0.6 if same else 1.0)  # تفاوت در برون/درون‌گرایی هم امتیاز مثبت داره (مکمل)
            strengths.append(STRENGTH_BANK["EI_same"] if same else STRENGTH_BANK["EI_diff"])
            if not same:
                weaknesses.append(WEAKNESS_BANK["EI_diff"])
        else:
            score += weights[axis] * (1.0 if same else 0.45)
            key_same = f"{axis}_same"
            key_diff = f"{axis}_diff"
            if same and key_same in STRENGTH_BANK:
                strengths.append(STRENGTH_BANK[key_same])
            elif not same:
                if key_same == "SN_same":
                    pass
                if key_diff in STRENGTH_BANK:
                    strengths.append(STRENGTH_BANK[key_diff])
                if key_diff in WEAKNESS_BANK:
                    weaknesses.append(WEAKNESS_BANK[key_diff])

    score = max(30, min(100, int(score)))
    suggestion = random.Random(type1 + type2).choice(SUGGESTIONS)
    return {"score": score, "strengths": strengths, "weaknesses": weaknesses, "suggestion": suggestion}
