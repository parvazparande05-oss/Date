def score_answers(answers: list[str]) -> str:
    """answers: لیستی هم‌طول با QUESTIONS، هرکدام 'a' یا 'b'."""
    counts = {"E": 0, "I": 0, "S": 0, "N": 0, "T": 0, "F": 0, "J": 0, "P": 0}
    for (axis, _, _), ans in zip(QUESTIONS, answers):
        letter = axis[0] if ans == "a" else axis[1]
        counts[letter] += 1
    result = ""
    result += "E" if counts["E"] >= counts["I"] else "I"
    result += "S" if counts["S"] >= counts["N"] else "N"
    result += "T" if counts["T"] >= counts["F"] else "F"
    result += "J" if counts["J"] >= counts["P"] else "P"
    return result


